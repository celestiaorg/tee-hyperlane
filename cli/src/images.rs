//! `teeism images`: build each origin's enclave image reproducibly with Nix, push it, and pin
//! its registry digest in the compose files and deploy/images.lock.
//!
//! The only command that writes those files, so they cannot drift apart, and `teeism enclaves
//! up` can check the pins against the code. A chain whose source still evaluates to its locked
//! store path is left alone: nothing is built or pushed.

use anyhow::{bail, Context, Result};
use std::collections::BTreeMap;
use std::path::PathBuf;

use crate::chains::{ENCLAVES, IMAGE_REPO};
use crate::ctx::Ctx;
use crate::out;
use crate::run::Cmd;

pub fn compose_file(ctx: &Ctx, target: &str) -> PathBuf {
    ctx.repo.join(format!("deploy/docker-compose.{target}.yml"))
}

fn lock_file(ctx: &Ctx) -> PathBuf {
    ctx.repo.join("deploy/images.lock")
}

const LOCK_HEADER: &str = "\
# <chain> <nix store path of the image> <registry digest>
# Written only by `teeism images`. `teeism enclaves up` refuses to deploy a chain whose
# current source no longer evaluates to its store path here.
";

const ALL_HEADER: &str = "\
# The measured configuration for the shared CVM: every origin's enclave, each on its own port.
# Generated by `teeism images` from deploy/docker-compose.<chain>.yml; do not edit.
#
# This file's hash becomes `compose-hash` in RTMR3, so every ISM attested from this CVM pins
# all of it: changing any one image here moves the identity of every chain in it. A chain
# deployed alone (`teeism enclaves up --chain <chain>`) measures only its own file instead.
services:
";

/// `chain -> (store path, digest)` from deploy/images.lock.
pub fn read_lock(ctx: &Ctx) -> Result<BTreeMap<String, (String, String)>> {
    let path = lock_file(ctx);
    let raw = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let mut out = BTreeMap::new();
    for line in raw.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.len() != 3 {
            bail!("{} has a malformed line: `{line}`", path.display());
        }
        out.insert(parts[0].to_string(), (parts[1].to_string(), parts[2].to_string()));
    }
    Ok(out)
}

fn write_lock(ctx: &Ctx, lock: &BTreeMap<String, (String, String)>) -> Result<()> {
    let mut s = LOCK_HEADER.to_string();
    for (chain, (path, digest)) in lock {
        s.push_str(&format!("{chain} {path} {digest}\n"));
    }
    std::fs::write(lock_file(ctx), s).context("writing deploy/images.lock")
}

/// The store path the current source would build for a chain. Evaluates, never builds.
pub fn out_path(ctx: &Ctx, chain: &str) -> Result<String> {
    Ok(Cmd::new(format!("evaluating the {chain} image"), "nix")
        .args(["eval", "--raw", &format!(".#image-{chain}.outPath")])
        .cwd(&ctx.repo)
        .output()?
        .trim()
        .to_string())
}

/// The digest a chain's compose file pins.
pub fn pinned_digest(ctx: &Ctx, chain: &str) -> Result<String> {
    let path = compose_file(ctx, chain);
    let raw = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let at = raw.find("tee-node@").with_context(|| format!("{} pins no tee-node image", path.display()))?;
    Ok(raw[at + "tee-node@".len()..].split_whitespace().next().unwrap_or("").to_string())
}

/// The shared CVM's compose: every chain's service exactly as its own file has it.
pub fn compose_all(ctx: &Ctx) -> Result<String> {
    let mut s = ALL_HEADER.to_string();
    for (chain, _) in ENCLAVES {
        let path = compose_file(ctx, chain);
        let raw = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
        let body = raw
            .split_once("\nservices:\n")
            .map(|(_, b)| b)
            .with_context(|| format!("{} has no `services:` block", path.display()))?;
        s.push_str(body);
    }
    Ok(s)
}

pub fn run(ctx: &Ctx, chains: &[String]) -> Result<()> {
    let chains: Vec<String> = if chains.is_empty() {
        ENCLAVES.iter().map(|(c, _)| c.to_string()).collect()
    } else {
        chains.to_vec()
    };
    let mut lock = read_lock(ctx)?;
    let mut pinned = Vec::new();
    for chain in &chains {
        crate::chains::enclave_port(chain)?;
        let out_path = out_path(ctx, chain)?;
        let digest = pinned_digest(ctx, chain)?;
        if let Some((p, d)) = lock.get(chain) {
            if *p == out_path && *d == digest {
                out::info(format!("{chain}: unchanged, still {}", out_path.rsplit('/').next().unwrap_or("")));
                continue;
            }
        }
        out::step(format!("{chain}: building {out_path}"));
        let result = format!("result-{chain}");
        Cmd::new(format!("building the {chain} image"), "nix")
            .args(["build", &format!(".#image-{chain}"), "-o", &result])
            .cwd(&ctx.repo)
            .run()?;
        let built = std::fs::canonicalize(ctx.repo.join(&result)).context("reading the nix result link")?;
        if built.to_string_lossy() != out_path {
            bail!("{chain}: nix built {} rather than {out_path}", built.display());
        }
        Cmd::new(format!("loading the {chain} image into docker"), "docker")
            .args(["load", "-i"])
            .arg(&built)
            .output()?;
        let tag = format!("{IMAGE_REPO}:reproducible-{chain}");
        let pushed = Cmd::new(format!("pushing {tag} (logged in? docker login ghcr.io -u jonas089)"), "docker")
            .args(["push", &tag])
            .output()?;
        // The digest the registry assigns, read off the push itself: the one Phala pulls and
        // the compose hash covers.
        let digest = pushed
            .split_whitespace()
            .skip_while(|w| *w != "digest:")
            .nth(1)
            .filter(|d| d.starts_with("sha256:") && d.len() == 71)
            .with_context(|| format!("{chain}: the push reported no digest:\n{pushed}"))?
            .to_string();
        let path = compose_file(ctx, chain);
        let raw = std::fs::read_to_string(&path)?;
        let old = format!("tee-node@{}", pinned_digest(ctx, chain)?);
        std::fs::write(&path, raw.replace(&old, &format!("tee-node@{digest}")))
            .with_context(|| format!("writing {}", path.display()))?;
        lock.insert(chain.clone(), (out_path, digest.clone()));
        write_lock(ctx, &lock)?;
        out::info(format!("{chain}: pinned {digest}"));
        pinned.push(chain.clone());
    }
    std::fs::write(compose_file(ctx, "all"), compose_all(ctx)?).context("writing deploy/docker-compose.all.yml")?;
    if pinned.is_empty() {
        out::ok("every image is pinned to what this source builds");
    } else {
        out::ok(format!(
            "pinned {}. Commit and push deploy/docker-compose.*.yml and deploy/images.lock before `teeism enclaves up`",
            pinned.join(", ")
        ));
    }
    Ok(())
}
