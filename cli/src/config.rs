//! `teeism config`: write the relayer's config (devnet/.state/coprocessor.toml) and the gas
//! oracle's (devnet/.state/gas-oracle.toml) from what this deployment created.
//!
//! Regenerated on every run, so editing either by hand does not survive. Endpoint defaults are
//! the live ones; each is overridable in devnet/.env by the name next to it.

use anyhow::{Context, Result};
use std::fmt::Write as _;

use crate::chains::{self, celestia as cel, EVM_CHAINS};
use crate::ctx::Ctx;
use crate::out;
use crate::state::Deployment;

/// The Base and Arbitrum archives: BASE_ARCHIVE / ARBITRUM_ARCHIVE as URLs, else Alchemy with
/// ALCHEMY_KEY (ALCHEMY_BASE_KEY, or the key file older hosts keep in .state). Only these two
/// `rpc` fields ever carry the metered key; logs and reads near the head use public endpoints.
fn archive(ctx: &Ctx, var: &str, alchemy_host: &str, fallback: &str) -> String {
    if let Some(url) = ctx.var(var) {
        return url;
    }
    let key = ctx
        .var("ALCHEMY_KEY")
        .or_else(|| ctx.var("ALCHEMY_BASE_KEY"))
        .or_else(|| std::fs::read_to_string(ctx.state_dir.join("alchemy-base-key")).ok().map(|s| s.trim().to_string()))
        .filter(|k| !k.is_empty());
    match key {
        Some(k) => format!("https://{alchemy_host}/v2/{k}"),
        None => fallback.to_string(),
    }
}

/// The relayer config, as TOML text.
pub fn coprocessor_toml(ctx: &Ctx, d: &Deployment) -> Result<String> {
    let mut s = String::new();
    let c = &d.celestia;
    let w = &mut s;
    writeln!(w, "# Generated by `teeism config` from devnet/.state/deployment.json; edits do not survive.")?;
    writeln!(w, "# See deploy/coprocessor.toml.example.")?;
    writeln!(w, "tick_secs = {}", ctx.var_or("TICK_SECS", "2"))?;
    writeln!(w, "proof_dir = \"{}\"", ctx.state_dir.join("proofs").display())?;
    writeln!(w, "api_listen = \"{}\"", ctx.var_or("API_LISTEN", "0.0.0.0:3001"))?;

    // The faucet pays from `user`, which holds the TIA and the teeUSD supply. Each grant stops
    // once the key would fall below its floor, so the account keeps a reserve.
    if let Some(denom) = d.teeusd_denom() {
        writeln!(w, "\n[faucet]\nchain = \"celestia\"\nkey = \"{}\"", ctx.var_or("FAUCET_KEY", "user"))?;
        writeln!(w, "grants = [")?;
        writeln!(
            w,
            "  {{ symbol = \"TIA\", denom = \"utia\", amount = {}, floor = {} }},",
            ctx.var_or("FAUCET_TIA", "5000000000"),
            ctx.var_or("FAUCET_TIA_FLOOR", "500000000000000")
        )?;
        writeln!(
            w,
            "  {{ symbol = \"teeUSD\", denom = \"{denom}\", amount = {}, floor = {} }},",
            ctx.var_or("FAUCET_TEEUSD", "20000000000"),
            ctx.var_or("FAUCET_TEEUSD_FLOOR", "1000000000000000")
        )?;
        writeln!(w, "]")?;
    }

    writeln!(w, "\n[chains.celestia]\nkind = \"celestia\"\ndomain = {}", cel::DOMAIN)?;
    writeln!(w, "rpc = \"{}\"", chains::celestia_rpc(ctx))?;
    writeln!(w, "mailbox = \"{}\"", c.mailbox.as_deref().unwrap_or(""))?;
    writeln!(w, "merkle_tree_hook = \"{}\"", c.merkle_hook.as_deref().unwrap_or(""))?;
    writeln!(w, "lag = 1\nchain_id = \"{}\"\nhome = \"{}\"", cel::CHAIN_ID, ctx.celestia_home().display())?;

    writeln!(w, "\n[chains.mocha]\nkind = \"celestia\"\ndomain = 1297040200")?;
    writeln!(w, "rpc = \"{}\"", ctx.var_or("MOCHA_RPC", "https://rpc.celestia-mocha.com"))?;

    for chain in &EVM_CHAINS {
        let (mailbox, hook) = match chain.canonical {
            Some(h) => (Some(h.mailbox), Some(h.merkle_hook)),
            None => {
                let e = d.evm(chain.name);
                (e.and_then(|e| e.mailbox), e.and_then(|e| e.merkle_hook))
            }
        };
        let (Some(mailbox), Some(hook)) = (mailbox, hook) else { continue };
        writeln!(w, "\n[chains.{}]\nkind = \"{}\"\ndomain = {}", chain.name, chain.kind, chain.domain)?;
        match chain.name {
            // Read from the host's own nodes: reth for execution, Lodestar for the beacon chain
            // (the only client that serves Gloas light-client data).
            "sepolia" => {
                writeln!(w, "rpc = \"{}\"", ctx.var_or("SEPOLIA_RPC", "http://127.0.0.1:8545"))?;
                writeln!(w, "beacon_rpc = \"{}\"", ctx.var_or("SEPOLIA_BEACON", "http://127.0.0.1:9596"))?;
                // Deliveries go through `rpc` unless this is set; whichever it is must be at the
                // head, or the ISM refuses an attestation newer than its block.
                if let Some(send) = ctx.var("SEPOLIA_SEND_RPC") {
                    writeln!(w, "send_rpc = \"{send}\"")?;
                }
            }
            "arbitrum" => {
                writeln!(w, "rpc = \"{}\"", archive(ctx, "ARBITRUM_ARCHIVE", "arb-sepolia.g.alchemy.com", "https://api.zan.top/arb-sepolia"))?;
                writeln!(w, "feed = \"{}\"", ctx.var_or("ARBITRUM_FEED", "wss://sepolia-rollup.arbitrum.io/feed"))?;
                // Serves eth_getLogs over a million blocks; publicnode caps at 50k.
                writeln!(w, "logs_rpc = \"{}\"", ctx.var_or("ARBITRUM_LOGS", "https://sepolia-rollup.arbitrum.io/rpc"))?;
                writeln!(w, "send_rpc = \"{}\"", chain.rpc(ctx))?;
            }
            "base" => {
                writeln!(w, "rpc = \"{}\"", archive(ctx, "BASE_ARCHIVE", "base-sepolia.g.alchemy.com", "https://sepolia.base.org"))?;
                writeln!(w, "p2p_port = {}", ctx.var_or("BASE_P2P_PORT", "9222"))?;
                writeln!(w, "logs_rpc = \"{}\"", chain.rpc(ctx))?;
                writeln!(w, "send_rpc = \"{}\"", chain.rpc(ctx))?;
            }
            "eden" => {
                writeln!(w, "celestia = \"mocha\"")?;
                writeln!(w, "da_rpc = \"{}\"", ctx.var_or("EDEN_DA_RPC", "http://localhost:26658"))?;
                writeln!(w, "rpc = \"{}\"", ctx.var_or("EDEN_ARCHIVE", "https://ev-reth-eden-testnet.binarybuilders.services:8545/"))?;
                writeln!(w, "logs_rpc = \"{}\"", chain.rpc(ctx))?;
                writeln!(w, "send_rpc = \"{}\"", chain.rpc(ctx))?;
            }
            other => anyhow::bail!("no relayer settings for chain {other}"),
        }
        writeln!(w, "mailbox = \"{mailbox}\"\nmerkle_tree_hook = \"{hook}\"")?;
    }

    // A route only once its ISM and its enclave exist.
    let enclave_url = |origin: &str| d.enclaves.chains.get(chains::enclave_for(origin)).map(|e| e.url.clone());
    let quote = |v: &[String]| v.iter().map(|r| format!("\"{r}\"")).collect::<Vec<_>>().join(", ");
    for chain in &EVM_CHAINS {
        let e = d.evm(chain.name);
        let (Some(ism), Some(url)) = (e.and_then(|e| e.ism), enclave_url("celestia")) else { continue };
        let routers: Vec<String> = [e.and_then(|e| e.tia_router), e.and_then(|e| e.teeusd_router)]
            .into_iter()
            .flatten()
            .map(|a| a.to_string())
            .collect();
        writeln!(w, "\n[[routes]]\nname = \"celestia-to-{0}\"\nfrom = \"celestia\"\nto = \"{0}\"", chain.name)?;
        writeln!(w, "enclave = \"{url}\"\nism = \"{ism}\"\nrouters = [{}]", quote(&routers))?;
    }
    for chain in &EVM_CHAINS {
        let (Some(ism), Some(url)) = (c.isms.get(chain.name), enclave_url(chain.name)) else { continue };
        let routers: Vec<String> = [c.tia_token.clone(), c.teeusd_token.clone()].into_iter().flatten().collect();
        writeln!(w, "\n[[routes]]\nname = \"{0}-to-celestia\"\nfrom = \"{0}\"\nto = \"celestia\"", chain.name)?;
        writeln!(w, "enclave = \"{url}\"\nism = \"{ism}\"\nrouters = [{}]", quote(&routers))?;
        // Sepolia is read from a full node, whose proofs at an old block slow down the further
        // back it is; about an hour of blocks keeps them to seconds however quiet the route.
        if chain.name == "sepolia" {
            writeln!(w, "max_lag = {}", ctx.var_or("SEPOLIA_MAX_LAG", "300"))?;
        }
    }
    Ok(s)
}

/// The gas oracle's config: what a transfer is charged for gas on the far side.
pub fn gas_oracle_toml(ctx: &Ctx, d: &Deployment) -> Result<Option<String>> {
    let Some(igp) = &d.celestia.igp else { return Ok(None) };
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "# Generated by `teeism config`; edits do not survive. See deploy/gas-oracle.toml.example.")?;
    writeln!(w, "# Once an hour is enough: between rounds the paymaster keeps the last values.")?;
    writeln!(w, "interval_secs = {}", ctx.var_or("GAS_ORACLE_INTERVAL", "3600"))?;
    writeln!(w, "igp_id = \"{igp}\"")?;
    writeln!(w, "celestia_rpc = \"{}\"", chains::celestia_rpc(ctx))?;
    writeln!(w, "chain_id = \"{}\"", cel::CHAIN_ID)?;
    writeln!(w, "local_price_id = \"celestia\"")?;
    for (chain, rpc, price_id) in [
        ("sepolia", "https://ethereum-sepolia-rpc.publicnode.com", "ethereum"),
        ("arbitrum", "https://arbitrum-sepolia-rpc.publicnode.com", "ethereum"),
        ("base", "https://base-sepolia-rpc.publicnode.com", "ethereum"),
        // Eden pays gas in TIA, so its price id is the local one and the ratio posted is one.
        ("eden", "https://rpc.testnet.eden.gateway.fm/", "celestia"),
    ] {
        let c = chains::evm(chain)?;
        writeln!(w, "\n[[destinations]]\nname = \"{}\"\ndomain = {}\nrpc = \"{rpc}\"", c.label, c.domain)?;
        // Measured: mailbox.process cost 89k to 127k across this deployment's transfers.
        writeln!(w, "decimals = 18\nprice_id = \"{price_id}\"\ngas_overhead = 150000")?;
    }
    Ok(Some(s))
}

pub fn write(ctx: &Ctx) -> Result<()> {
    let d = ctx.deployment()?;
    let path = ctx.coprocessor_config();
    std::fs::create_dir_all(ctx.state_dir.join("proofs"))?;
    std::fs::write(&path, coprocessor_toml(ctx, &d)?).with_context(|| format!("writing {}", path.display()))?;
    out::info(format!("wrote {}", path.display()));
    if let Some(g) = gas_oracle_toml(ctx, &d)? {
        let p = ctx.state_dir.join("gas-oracle.toml");
        std::fs::write(&p, g).with_context(|| format!("writing {}", p.display()))?;
        out::info(format!("wrote {}", p.display()));
    }
    Ok(())
}
